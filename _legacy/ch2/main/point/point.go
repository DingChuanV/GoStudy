package main

import "fmt"

// 函数形参p的类型是*int：说明p是一个指针，只能存int类型变量的地址
func changeValue(p *int) {
	// 核心操作：解引用p，修改p指向的内存的值
	*p = 10
}

func main() {
	// 第1步：定义变量a，赋值为1
	var a int = 1
	// 【内存对应】
	// 系统给a分配一块内存，给它分配了唯一的门牌号（内存地址）：0x0843A040
	// 这块内存里，存的数值是 1，对应图里右侧第一格的内容

	// 第2步：调用函数，把a的地址传给changeValue
	changeValue(&a)
	// 【内存对应】
	// &a 拿到了a的门牌号 0x0843A040
	// Go是值传递：把这个门牌号拷贝了一份，传给函数的形参p
	// 系统给形参p也分配了一块内存，门牌号是 0x0843A06A
	// p的内存里，存的内容就是a的门牌号 0x0843A040，对应图里右侧第三格的内容

	// 第4步：打印a的值，最终输出 a = 10
	fmt.Println("a = ", a)
}

// 第3步：进入changeValue函数执行
func changeValue(p *int) {
	*p = 10
	// 【内存对应】
	// *p 就是解引用：拿着p里存的门牌号0x0843A040，找到a的内存空间
	// 把10写入这块内存，直接覆盖了原来的1
	// 这一步，直接修改了main函数里原变量a的内存内容
}
